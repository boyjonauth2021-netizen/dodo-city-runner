export const routeOf = (uid) => ROUTES[uid];
/** Game-z (player z is negative) to metres along the OSM path. */
export function distAlong(level, z) {
  const r = ROUTES[level && level.uid]; if (!r || !r.lengthM) return 0;
  const goal = Math.max(40, (level && level.goal) || r.lengthM);
  return Math.max(0, Math.min(r.lengthM, (-z / goal) * r.lengthM));
}
export function sectionAt(level, z) {
  const r = ROUTES[level && level.uid]; if (!r) return null;
  const dist = distAlong(level, z);
  let sec = (r.sections && r.sections[0]) || {};
  for (const x of (r.sections || [])) if (x.at <= dist) sec = x;
  const road = (r.roads || []).reduce((a, x) => x.at <= dist ? x : a, r.roads && r.roads[0]);
  const lms = r.landmarks || [];
  const here = lms.filter((l) => Math.abs(l.at - dist) < 55);
  const next = lms.find((l) => l.at > dist + 8);
  const prev = [...lms].reverse().find((l) => l.at <= dist + 8);
  const turn = (r.turns || []).find((t) => Math.abs(t.at - dist) < 40);
  const st = (r.stations || []).find((s) => Math.abs(s.at - dist) < 80);
  return { dist, sec, road, roadName: (road && road.name) || (sec && sec.road) || r.routeName || "", sea: (sec && sec.sea) || r.sea, heading: sec && sec.heading, turn, landmarks: here, next, prev, station: st, route: r, density: (sec && sec.density) || "medium" };
}
